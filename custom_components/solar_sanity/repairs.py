"""Repairs — the primary interface for findings.

A finding belongs in the Repairs panel, not a log line and not a notification.
It is a thing the user can act on, it has a fix flow, and it disappears when the
condition clears.

Two rules that are easy to get wrong: issues do **not** self-heal, so we delete
them the moment a finding goes away; and ``is_persistent`` stays false so a
configuration fixed while Home Assistant was stopped silently drops the issue on
restart rather than resurrecting a solved problem.
"""

from __future__ import annotations

import logging
from typing import Any

from homeassistant.components.repairs import ConfirmRepairFlow, RepairsFlow
from homeassistant.config_entries import ConfigEntry
from homeassistant.core import HomeAssistant
from homeassistant.helpers import issue_registry as ir

from .analysis.model import AnalysisReport, Finding, Severity
from .const import DOMAIN, EVENT_FINDING_CLEARED, EVENT_FINDING_RAISED, OPT_CORRECTIONS

_LOGGER = logging.getLogger(__name__)


def _translation_key(finding: Finding) -> str:
    """Which of the four issue templates this finding renders through.

    Home Assistant renders ``fix_flow`` for an issue with a Fix button and
    ``description`` for one without, and its own schema refuses to let a single
    key carry both. A finding that offers no correction — which is most of them,
    because the honest answer is usually a configuration change rather than an
    internal override — showed its headline and nothing else until it got a key
    of its own.
    """
    stem = "finding_question" if finding.severity is Severity.QUESTION else "finding"
    return stem if finding.offered_correction is not None else f"{stem}_unfixable"


def issue_id_for(entry: ConfigEntry, code: str) -> str:
    return f"{code}_{entry.entry_id}"


def issue_ids_for_entry(hass: HomeAssistant, entry_id: str) -> set[str]:
    """Every issue this integration currently owns for one config entry.

    Issue ids are suffixed with the entry id, which is a ULID, so the suffix
    test cannot collide across entries.
    """
    return {
        issue.issue_id
        for issue in ir.async_get(hass).issues.values()
        if issue.domain == DOMAIN and issue.issue_id.endswith(entry_id)
    }


async def async_sweep_orphans(hass: HomeAssistant, live_entry_ids: set[str]) -> None:
    """Drop issues belonging to entries that are no longer configured.

    ``async_remove_issues`` handles removal from now on, but it only runs at the
    moment an entry goes, so anything orphaned before it shipped is stranded
    forever: every other path here reconciles against *this* entry's id, and an
    old issue does not carry it. The reference installation has one such card,
    for an entry deleted half an hour before the removal hook existed, and
    nothing would ever have cleared it.

    Its Fix button leads to a flow that can only abort, so it is not merely
    untidy — it is a repair the user cannot action and cannot dismiss for good.
    """
    stale = {
        issue.issue_id
        for issue in ir.async_get(hass).issues.values()
        if issue.domain == DOMAIN
        and not any(issue.issue_id.endswith(entry_id) for entry_id in live_entry_ids)
    }
    for issue_id in stale:
        ir.async_delete_issue(hass, DOMAIN, issue_id)


async def async_remove_issues(hass: HomeAssistant, entry_id: str) -> None:
    """Drop every issue belonging to an entry that no longer exists.

    Not on unload — a reload unloads too, and flapping the issue would lose the
    user's dismissal. Only on removal, where the alternative is a repair card
    for an installation that is gone, whose fix flow can do nothing but abort.
    """
    for issue_id in issue_ids_for_entry(hass, entry_id):
        ir.async_delete_issue(hass, DOMAIN, issue_id)


async def async_sync_issues(
    hass: HomeAssistant, entry: ConfigEntry, report: AnalysisReport | None
) -> None:
    """Make the Repairs panel match the current report exactly.

    One finding at a time, by design: an uncorrected fault dominates the
    residual and makes every other statistic meaningless, so a list of five
    would mostly be noise generated by the first one.
    """
    existing = issue_ids_for_entry(hass, entry.entry_id)

    finding = report.finding if report else None
    wanted: set[str] = set()

    if finding is not None and finding.severity is not Severity.NOTE:
        issue_id = issue_id_for(entry, finding.code)
        wanted.add(issue_id)

        if issue_id not in existing:
            hass.bus.async_fire(
                EVENT_FINDING_RAISED,
                {
                    "entry_id": entry.entry_id,
                    "code": finding.code,
                    "confidence": finding.confidence.value,
                    "channels": list(finding.channel_keys),
                },
            )

        ir.async_create_issue(
            hass,
            DOMAIN,
            issue_id,
            is_fixable=finding.offered_correction is not None,
            is_persistent=False,
            severity=ir.IssueSeverity.WARNING,
            # Four keys, not two. Home Assistant renders `fix_flow` for an issue
            # with a Fix button and `description` for one without, and its
            # schema refuses to let a single key carry both — so a finding that
            # offers no correction, which is most of them, showed its headline
            # and nothing else until it got a key of its own.
            translation_key=_translation_key(finding),
            translation_placeholders={
                "headline": finding.headline,
                "detail": finding.detail,
                "source_fix": finding.source_fix or "",
            },
            data={
                "entry_id": entry.entry_id,
                "code": finding.code,
                "channel_key": finding.channel_keys[0] if finding.channel_keys else "",
                "correction_kind": (
                    finding.offered_correction.kind if finding.offered_correction else ""
                ),
                "correction_factor": (
                    finding.offered_correction.factor
                    if finding.offered_correction and finding.offered_correction.factor
                    else 0.0
                ),
            },
        )

    for stale in existing - wanted:
        ir.async_delete_issue(hass, DOMAIN, stale)
        hass.bus.async_fire(EVENT_FINDING_CLEARED, {"entry_id": entry.entry_id, "issue_id": stale})


class ApplyCorrectionFlow(RepairsFlow):
    """Offer the correction — and make it obvious what is and is not changing.

    Corrections are framed as "applied so I can keep checking", never as
    "fixed". The underlying sensor is still wrong everywhere that matters: the
    Energy Dashboard, the user's automations, their own reconciliation. Papering
    over it inside this integration while leaving the rest of their system
    broken would be the exact inversion of what this product promises.
    """

    def __init__(self, data: dict[str, Any]) -> None:
        self._data = data

    async def async_step_init(self, user_input: dict[str, str] | None = None) -> Any:
        return await self.async_step_confirm()

    async def async_step_confirm(self, user_input: dict[str, str] | None = None) -> Any:
        if user_input is None:
            return self.async_show_form(step_id="confirm", data_schema=None)

        entry = self.hass.config_entries.async_get_entry(self._data.get("entry_id", ""))
        if entry is None:
            return self.async_abort(reason="entry_gone")

        corrections = list(entry.options.get(OPT_CORRECTIONS, []))
        corrections.append(
            {
                "channel_key": self._data.get("channel_key"),
                "kind": self._data.get("correction_kind"),
                "factor": self._data.get("correction_factor") or None,
            }
        )
        self.hass.config_entries.async_update_entry(
            entry, options={**entry.options, OPT_CORRECTIONS: corrections}
        )
        self.hass.config_entries.async_schedule_reload(entry.entry_id)
        return self.async_create_entry(data={})


async def async_create_fix_flow(
    hass: HomeAssistant, issue_id: str, data: dict[str, Any] | None
) -> RepairsFlow:
    """Return the flow for a repair. Only correctable findings get a real one."""
    if data and data.get("correction_kind"):
        return ApplyCorrectionFlow(data)
    return ConfirmRepairFlow()
